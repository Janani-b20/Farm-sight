/**
 * Universal Scheme Translation Helper
 * Safely looks up scheme by scheme_id, id, short_name, or scheme_name.
 * Supports both signatures:
 * getSchemeTranslation(scheme, lang)
 * getSchemeTranslation(scheme_id, lang, scheme)
 */
export function getSchemeTranslation(
  schemeOrId: any,
  lang: 'en' | 'ta' | 'hi',
  fallbackScheme?: any
) {
  if (!schemeOrId && !fallbackScheme) {
    return {
      benefit: '',
      eligibilityNote: '',
      whyRecommended: [],
      documents: [],
      relevance: '',
    };
  }

  const scheme = typeof schemeOrId === 'object' && schemeOrId !== null
    ? schemeOrId
    : (fallbackScheme || { scheme_id: schemeOrId });

  const idKey = (scheme.scheme_id || scheme.id || (typeof schemeOrId === 'string' ? schemeOrId : '') || '').toLowerCase();
  const shortKey = (scheme.short_name || '').toLowerCase();
  const nameKey = (scheme.scheme_name || '').toLowerCase();

  const entry =
    SCHEME_TRANSLATIONS[idKey] ||
    SCHEME_TRANSLATIONS[shortKey] ||
    SCHEME_TRANSLATIONS[nameKey];

  if (lang === 'en' || !entry) {
    const rawReasons = scheme.why_recommended || scheme.whyRecommended || [];
    return {
      benefit: scheme.benefit || '',
      eligibilityNote: scheme.eligibility_note || scheme.eligibilityNote || '',
      whyRecommended: rawReasons,
      documents: scheme.documents || [],
      relevance: scheme.relevance || '',
    };
  }

  const targetLang: 'ta' | 'hi' = lang;
  const localized = entry[targetLang];
  const relMap = RELEVANCE_MAP[scheme.relevance];
  const localizedRelevance = relMap ? relMap[targetLang] : scheme.relevance || '';

  const rawReasons = scheme.why_recommended || scheme.whyRecommended || (localized && localized.whyRecommended) || [];
  const localizedReasons = rawReasons.map((r: string) => {
    const rMatch = REASON_TRANSLATIONS[r];
    if (rMatch && rMatch[targetLang]) {
      return rMatch[targetLang];
    }
    return r;
  });

  return {
    benefit: localized?.benefit || scheme.benefit || '',
    eligibilityNote: localized?.eligibilityNote || scheme.eligibility_note || '',
    whyRecommended: localizedReasons.length > 0 ? localizedReasons : localized?.whyRecommended || [],
    documents: localized?.documents && localized.documents.length > 0 ? localized.documents : scheme.documents || [],
    relevance: localizedRelevance,
  };
}
